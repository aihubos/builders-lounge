import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = process.cwd();
const sources = [
  "lounge/tokens.css",
  "lounge/base.css",
  "lounge/topbar.css",
  "lounge/lounge.css",
  "lounge/portal.css",
  "lounge/js/pages/home.css",
  "lounge/community.css",
  "lounge/platform.css",
];

const sections = await Promise.all(sources.map(async (file) => {
  const css = await readFile(resolve(root, file), "utf8");
  return `/* ${file} */\n${css.trim()}\n`;
}));

await writeFile(
  resolve(root, "lounge/core.css"),
  `/* Generated by scripts/bundle-css.mjs. Edit the source CSS files. */\n\n${sections.join("\n")}`,
);

console.log("Lounge 첫 화면 CSS 묶음 갱신");
